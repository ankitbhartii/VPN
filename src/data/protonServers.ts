export function buildCountryGroups(servers: LogicalServer[]): CountryGroup[] {
  const map = new Map<string, CountryGroup>();

  for (const srv of servers) {
    const code = srv.exitCountryCode;
    let group = map.get(code);
    if (!group) {
      group = {
        countryCode: code,
        countryName: srv.exitCountryName,
        flag: COUNTRY_FLAGS[code] || '🌐',
        coordinates: srv.exitCoords,
        cities: [],
        servers: [],
        secureCoreServers: [],
        hasFreeServers: false,
        hasP2P: false,
        hasTor: false,
      };
      map.set(code, group);
    }

    const isSecureCore = srv.features.includes(ServerFeature.SecureCore);
    if (isSecureCore) {
      group.secureCoreServers.push(srv);
    } else {
      group.servers.push(srv);
      if (!group.cities.includes(srv.city)) {
        group.cities.push(srv.city);
      }
    }

    if (srv.tier === 0) group.hasFreeServers = true;
    if (srv.features.includes(ServerFeature.P2P)) group.hasP2P = true;
    if (srv.features.includes(ServerFeature.Tor)) group.hasTor = true;
  }

  return Array.from(map.values()).sort((a, b) => a.countryName.localeCompare(b.countryName));
}

